def label(index: int) -> str:
    """「凝素领域·陨翼云渊（迅刀）」；没登记的写明第几个，不编名字。"""
    hit = FORGERY.get(int(index))
    if not hit:
        return f"凝素领域（第 {index} 个，对照表没登记）"
    return f"凝素领域·{hit[0]}（{hit[1]}）"


def reward(index: int) -> str:
    """产出：这个副本给哪种武器的突破材料。"""
    hit = FORGERY.get(int(index))
    return f"{hit[1]}突破材料" if hit else "武器突破材料"
